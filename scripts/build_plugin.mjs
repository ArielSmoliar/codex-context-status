// Build a self-contained Git-distributed plugin. Never include local session data.
import {build} from 'esbuild';
import {readFile, writeFile, mkdir, readdir, rm, copyFile, access} from 'node:fs/promises';
import {dirname, join, relative, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const output = join(root, 'plugins/context-status');
const skill = join(output, 'skills/context-status');
// Explicit allowlist: adding repository files cannot silently publish them.
const files = [
  'SKILL.md', 'agents/openai.yaml', 'assets/inspector.html',
  'scripts/context_status.py', 'scripts/mcp_snapshot.py', 'scripts/render_status.py',
  'references/telemetry.md', 'references/compatibility.md', 'references/handoffs.md',
  'references/plugin.md', 'mcp/inspector.html',
];

await rm(output, {recursive: true, force: true});
await mkdir(skill, {recursive: true});
for (const name of files) {
  const target = join(skill, name);
  await mkdir(dirname(target), {recursive: true});
  await copyFile(join(root, name), target);
}
// Packaged installations must use Codex's plugin lifecycle, not the standalone installer.
const source = await readFile(join(root, 'SKILL.md'), 'utf8');
const old = 'For installation or upgrade requests, read [references/installation.md](references/installation.md). The setup helper previews by default, preserves local conflicts, and prints registration commands without executing them. Do not run it during an ordinary context-status report.';
if (!source.includes(old)) throw new Error('Review the packaged installation instructions after changing SKILL.md.');
await writeFile(join(skill, 'SKILL.md'), source.replace(old,
  'This copy is installed as a Codex plugin. For setup, upgrades, migration, or removal, read [references/plugin.md](references/plugin.md). Use the Codex plugin lifecycle; do not create a second standalone skill or MCP registration.')
  .replace('## Default: MCP App inspector with in-place Refresh',
    '## Plugin data directory check\n\nBefore calling the plugin MCP tool, resolve the current chat’s CODEX_HOME via the shell (default ~/.codex). This plugin’s MCP server supports only the default ~/.codex directory on the tested Codex release; the host does not forward custom CODEX_HOME settings. If a different home is configured, do not call the plugin MCP tools. Explain the limitation and use the inline fallback below with --codex-home set to that exact known directory. For in-place refresh with custom homes, follow the standalone installation link in references/plugin.md. Never guess another directory.\n\n## Default: MCP App inspector with in-place Refresh'));
// Reference-only documents outside the runtime allowlist remain readable online.
for (const name of files.filter(name => name.endsWith('.md'))) {
  let markdown = await readFile(join(skill, name), 'utf8');
  for (const match of markdown.matchAll(/\]\(([^)]+)\)/g)) {
    const target = match[1];
    if (/^(?:[a-z]+:|#)/i.test(target)) continue;
    const [path, anchor] = target.split('#');
    try {await access(resolve(skill, dirname(name), path));}
    catch (error) {
      if (error.code !== 'ENOENT') throw error;
      const sourcePath = resolve(root, dirname(name), path);
      await access(sourcePath); // Fail on a broken source reference too.
      const url = `https://github.com/ArielSmoliar/codex-context-status/blob/main/${relative(root, sourcePath)}${anchor ? '#'+anchor : ''}`;
      markdown = markdown.replaceAll(`](${target})`, `](${url})`);
    }
  }
  await writeFile(join(skill, name), markdown);
}
for (const name of ['plugin.json', 'mcp.json']) await copyFile(join(root, 'packaging', name), join(output, name));

const result = await build({
  absWorkingDir: root, entryPoints: ['mcp/server.mjs'],
  outfile: join(skill, 'mcp/server.mjs'), bundle: true, platform: 'node',
  format: 'esm', target: 'node20', metafile: true, legalComments: 'inline',
  // Dependencies containing CommonJS modules need require when bundled into ESM.
  banner: {js: "// Generated by npm run build:plugin; edit mcp/server.mjs instead.\nimport {createRequire as bundledCreateRequire} from 'node:module';\nconst require = bundledCreateRequire(import.meta.url);"},
});

// Preserve licenses for every third-party package actually included by esbuild.
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue;
  let dir = dirname(resolve(root, input));
  while (dir !== root) {
    try {
      const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
      if (pkg.name && pkg.version) { packages.set(pkg.name, {dir, pkg}); break; }
    } catch (error) { if (error.code !== 'ENOENT') throw error; }
    const parent = dirname(dir);
    if (parent === dir) throw new Error(`Cannot locate dependency license for ${input}`);
    dir = parent;
  }
}
let notices = '# Bundled third-party software\n\nGenerated by scripts/build_plugin.mjs. Applies to bundled dependencies only.\n';
for (const [name, {dir, pkg}] of [...packages].sort(([a], [b]) => a.localeCompare(b))) {
  const licenses = (await readdir(dir)).filter(name => /^(license|copying|notice)(\.|$)/i.test(name)).sort();
  if (!licenses.length) throw new Error(`Missing license text for ${name}`);
  notices += `\n## ${name} ${pkg.version} (${pkg.license})\n`;
  for (const file of licenses) notices += `\n${await readFile(join(dir, file), 'utf8')}\n`;
}
await writeFile(join(output, 'THIRD_PARTY_NOTICES.md'), notices);
console.log(`Built ${relative(root, output)} with ${packages.size} bundled dependency licenses.`);
